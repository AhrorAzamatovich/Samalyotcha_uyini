import os, sys, shutil, subprocess, textwrap

BASE  = os.path.dirname(os.path.abspath(__file__))
DIST  = os.path.join(BASE, "dist")
BUILD = os.path.join(BASE, "_build_tmp")
SPEC  = os.path.join(BASE, "samalyotcha.spec")

# ─── ASSET PAPKALARINI TEKSHIRISH ─────────────────────────────────────────────

def ensure_assets():
    ai = os.path.join(BASE, "assets", "images")
    os.makedirs(ai, exist_ok=True)
    for src_name, dst_name in [("1.png", "player.png"), ("3.png", "enemy.png")]:
        src = os.path.join(BASE, src_name)
        dst = os.path.join(ai, dst_name)
        if os.path.exists(src) and not os.path.exists(dst):
            shutil.copy2(src, dst)
            print(f"  [asset] {src_name} -> assets/images/{dst_name}")
    return ai


