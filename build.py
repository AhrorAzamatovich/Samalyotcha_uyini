# ─── BUILD ────────────────────────────────────────────────────────────────────

def check_pyinstaller():
    try:
        import PyInstaller
        print(f"  PyInstaller: {PyInstaller.__version__}")
        return True
    except ImportError:
        return False

def check_pygame():
    try:
        import pygame
        print(f"  pygame: {pygame.__version__}")
        return True
    except ImportError:
        return False

def clean():
    for p in [DIST, BUILD]:
        if os.path.exists(p):
            shutil.rmtree(p)
            print(f"  [clean] {p}")
    if os.path.exists(SPEC):
        os.remove(SPEC)


def build():
    print()
    print("=" * 65)
    print("  SAMALYOTCHA  —  STANDALONE EXE BUILD")
    print("=" * 65)

    # Kutubxonalarni tekshirish
    print("\n[Tekshirish]")
    ok = True
    if not check_pygame():
        print("  ❌ pygame topilmadi!")
        print("     pip install pygame")
        ok = False
    if not check_pyinstaller():
        print("  ❌ PyInstaller topilmadi!")
        print("     pip install pyinstaller")
        ok = False
    if not ok:
        sys.exit(1)

    print("\n[1/4]  Eski build fayllari o'chirilmoqda...")
    clean()

    print("\n[2/4]  Asset fayllar tayyorlanmoqda...")
    assets_dir = ensure_assets()

    print("\n[3/4]  .spec fayl yozilmoqda...")
    write_spec(assets_dir)

    print("\n[4/4]  PyInstaller ishga tushirilmoqda...")
    print("       (Bu 2-5 daqiqa vaqt olishi mumkin...)\n")

    ret = subprocess.run(
        [
            sys.executable, "-m", "PyInstaller",
            "--distpath", DIST,
            "--workpath", BUILD,
            "--noconfirm",
            "--clean",
            SPEC,
        ],
        cwd=BASE,
        capture_output=False,
    )

    print()
    print("=" * 65)
    if ret.returncode == 0:
        exe = os.path.join(DIST, "Samalyotcha", "Samalyotcha.exe")
        folder = os.path.join(DIST, "Samalyotcha")

        if os.path.exists(exe):
            mb = os.path.getsize(exe) / 1024 / 1024
            # Papka umumiy hajmi
            total = sum(
                os.path.getsize(os.path.join(dp, f))
                for dp, dn, fns in os.walk(folder)
                for f in fns
            ) / 1024 / 1024

            print(f"  ✅  BUILD MUVAFFAQIYATLI YAKUNLANDI!")
            print(f"")
            print(f"  📂  Papka  : {folder}")
            print(f"  🎮  EXE    : Samalyotcha.exe  ({mb:.1f} MB)")
            print(f"  📦  Jami   : ~{total:.0f} MB")
            print(f"")
            print(f"  ─────────────────────────────────────────────")
            print(f"  📋  Ko'chirish uchun:")
            print(f"      dist\\Samalyotcha\\  papkasini butunligicha")
            print(f"      istalgan Windows kompyuterga ko'chiring.")
            print(f"      Python, pygame — O'RNATISH KERAK EMAS!")
            print(f"  ─────────────────────────────────────────────")
        else:
            print(f"  ✅  Build tugadi. Natija: {DIST}/")
    else:
        print("  ❌  BUILD XATO BILAN TUGADI!")
        print()
        print("  Mumkin bo'lgan sabab va yechimlar:")
        print("  1. pip install --upgrade pyinstaller")
        print("  2. pip install --upgrade pygame")
        print("  3. Antivirus o'chirib ko'ring (EXE ni bloklashi mumkin)")
        print("  4. Administrator sifatida ishga tushiring")
        sys.exit(1)

    print("=" * 65)
    print()


if __name__ == "__main__":
    build()
