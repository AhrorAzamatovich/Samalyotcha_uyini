"""
build.py  —  Samalyotcha O'yini uchun STANDALONE EXE yaratish.

Talablar:
    pip install pygame pyinstaller

Ishlatish:
    python build.py

Natija:
    dist/Samalyotcha/Samalyotcha.exe   (--onedir: tez ishga tushadi)

Har qanday Windows kompyuterga ko'chirilishi mumkin.
Python, pygame, boshqa hech narsa o'rnatish shart emas.
"""
import os, sys, shutil, subprocess, textwrap

BASE  = os.path.dirname(os.path.abspath(__file__))
DIST  = os.path.join(BASE, "dist")
BUILD = os.path.join(BASE, "_build_tmp")
SPEC  = os.path.join(BASE, "samalyotcha.spec")

# ─── SPEC FAYL ────────────────────────────────────────────────────────────────
SPEC_CONTENT = textwrap.dedent(f"""\
# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by build.py — DO NOT EDIT MANUALLY

block_cipher = None

a = Analysis(
    [r'{os.path.join(BASE, "main.py")}'],
    pathex=[r'{BASE}'],
    binaries=[],
    datas=[
        (r'{os.path.join(BASE, "assets", "images")}', 'assets/images'),
    ],
    hiddenimports=[
        'pygame', 'pygame.mixer', 'pygame.font', 'pygame.image',
        'pygame.transform', 'pygame.sndarray', 'pkg_resources.py2_warn',
    ],
    hookspath=[],
    runtime_hooks=[],
    excludes=[
        'numpy', 'scipy', 'matplotlib', 'tkinter', 'PIL',
        'IPython', 'setuptools', 'distutils',
    ],
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='Samalyotcha',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    console=False,
    icon=None,
)

coll = COLLECT(
    exe,
    a.binaries,
    a.zipfiles,
    a.datas,
    strip=False,
    upx=True,
    upx_exclude=[],
    name='Samalyotcha',
)
""")


def clean():
    for p in [DIST, BUILD]:
        if os.path.exists(p): shutil.rmtree(p); print(f"  [clean] {p}")
    if os.path.exists(SPEC): os.remove(SPEC)

def write_spec():
    with open(SPEC, "w", encoding="utf-8") as f:
        f.write(SPEC_CONTENT)
    print(f"  [spec]  {SPEC}")

def ensure_assets():
    ai = os.path.join(BASE, "assets", "images")
    os.makedirs(ai, exist_ok=True)
    # 1.png va 3.png ni assets/images ga ko'chir (agar hali ko'chirilmagan bo'lsa)
    for src_name, dst_name in [("1.png","player.png"),("3.png","enemy.png")]:
        src = os.path.join(BASE, src_name)
        dst = os.path.join(ai, dst_name)
        if os.path.exists(src) and not os.path.exists(dst):
            shutil.copy2(src, dst); print(f"  [asset] {src_name} → assets/images/{dst_name}")

def build():
    print("\n" + "═"*62)
    print("  SAMALYOTCHA  —  STANDALONE EXE BUILD (PyInstaller)")
    print("═"*62)

    # PyInstaller borligini tekshirish
    try:
        import PyInstaller
    except ImportError:
        print("\n❌  PyInstaller topilmadi. O'rnatish:")
        print("     pip install pyinstaller")
        sys.exit(1)

    print("\n[1/4]  Eski build fayllari o'chirilmoqda...")
    clean()

    print("\n[2/4]  Asset fayllar tayyorlanmoqda...")
    ensure_assets()

    print("\n[3/4]  .spec fayl yozilmoqda...")
    write_spec()

    print("\n[4/4]  PyInstaller ishga tushirilmoqda...\n")
    ret = subprocess.run(
        [sys.executable, "-m", "PyInstaller",
         "--distpath", DIST,
         "--workpath", BUILD,
         "--noconfirm",
         "--clean",
         SPEC],
        cwd=BASE,
    )

    print("\n" + "═"*62)
    if ret.returncode == 0:
        exe = os.path.join(DIST, "Samalyotcha", "Samalyotcha.exe")
        if os.path.exists(exe):
            mb = os.path.getsize(exe) / 1024 / 1024
            print(f"  ✅  Muvaffaqiyatli!")
            print(f"  📦  EXE: {exe}")
            print(f"  📏  Hajm: {mb:.1f} MB")
            print(f"\n  📁  Bu papkani istalgan Windows kompyuterga")
            print(f"      ko'chiring va Samalyotcha.exe ni ishga tushiring.")
            print(f"      Python, pygame  —  KERAK EMAS!")
        else:
            print(f"  ✅  Build tugadi: {DIST}/")
    else:
        print("  ❌  Build xato. Yuqoridagi xato xabarini ko'ring.")
        sys.exit(1)
    print("═"*62)


if __name__ == "__main__":
    build()
